# 复利 vs 单利对比程序（交互式）
#
# 复利公式: A_c = P * (1 + r)^n
#   每期利息计入本金, 下一期按新本金计息（利滚利）
#
# 单利公式: A_s = P * (1 + r * n)
#   每期利息只按原始本金计算, 不并入本金
#
# 其中:
#   P  = 本金
#   r  = 年利率
#   n  = 存款年数
#   A_c= 复利终值
#   A_s= 单利终值

# 第 1 步: 用户输入本金 P
P = float(input("请输入本金（元）: "))

# 第 2 步: 用户输入年利率 r, 并做合法性校验
while True:
    r = float(input("请输入年利率（如 0.05 表示 5%）: "))
    if r < 0:  # 利率为负, 不合法
        print("利率不能为负, 请重新输入。")
    else:  # 利率合法, 退出循环
        break

# 第 3 步: 定义要对比的年限列表
years_list = [10, 20, 30]

# 第 4 步: 打印表头
# 使用 :<12 左对齐占 12 字符宽, 让列整齐
print("-" * 56)
print(f"{'年限(年)':<12}{'复利终值':<16}{'单利终值':<16}{'差额':<12}")
print("-" * 56)

# 第 5 步: 逐行计算并输出对比表
for n in years_list:
    # 复利终值: 本金 × (1+利率)^年数
    A_c = P * (1 + r) ** n
    # 单利终值: 本金 × (1 + 利率×年数)
    A_s = P * (1 + r * n)
    # 差额 = 复利终值 - 单利终值
    diff = A_c - A_s
    # 输出该行, 三项金额均保留两位小数
    print(f"{n:<12}{A_c:<16.2f}{A_s:<16.2f}{diff:<12.2f}")

print("-" * 56)
