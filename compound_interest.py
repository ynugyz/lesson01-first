# 复利计算公式：A = P * (1 + r/n)^(n*t)
# 其中：
#   A = 最终本息和（Final Amount）
#   P = 本金（Principal）
#   r = 年利率（Annual Interest Rate，小数形式，如 5% 写成 0.05）
#   n = 每年复利次数（Number of times interest is compounded per year）
#   t = 存款年数（Number of years）

# ============== 交互式输入部分 ==============

# 第一步：输入本金 P
# input() 读取用户输入的字符串，float() 将其转为浮点数
P = float(input("请输入本金（元）："))

# 第二步：输入年利率，并校验"利率不能为负"
# 使用 while True 无限循环，直到输入合法利率才 break 退出
# 用户按"5 表示 5%"这种百分比形式输入，更直观
while True:
    r_input = float(input("请输入年利率（如 5 表示 5%）："))
    # 校验：利率为负数时不合法，提示并重新输入
    if r_input < 0:
        print("利率不能为负，请重新输入。")
        continue  # 跳过本次循环剩余部分，重新让用户输入
    break  # 利率合法，退出循环

# 第三步：输入存款年限 t
# 年限一般为整数，用 int() 转换
t = int(input("请输入存款年限（年）："))

# 第四步：设定每年复利次数 n（按题意每年复利 1 次）
n = 1

# ============== 公式计算部分 ==============

# 第五步：把用户输入的百分比利率转为小数形式
# 例如用户输入 5（表示 5%），则 r = 5 / 100 = 0.05
r = r_input / 100

# 第六步：计算单期利率 r/n
# 每年复利 1 次，所以 r/n = r/1 = r
# 表示每个复利周期内的实际利率
period_rate = r / n

# 第七步：计算复利周期总数 n*t
# 总复利次数 = 每年次数 × 年数
periods = n * t

# 第八步：计算 (1 + r/n)^(n*t)
# 1 + period_rate 表示一个周期后本金增长到的倍数
# 例如 1.05 表示每期本金变为原来的 1.05 倍
# 连乘 periods 次，体现"利滚利"的复利效应
growth_factor = (1 + period_rate) ** periods

# 第九步：套用复利公式 A = P * (1 + r/n)^(n*t)
# 本金乘以增长倍数，得到最终本息和
A = P * growth_factor

# 第十步：保留两位小数
# round(x, 2) 表示对 x 四舍五入保留 2 位小数
final_amount = round(A, 2)

# ============== 结果输出部分 ==============

# 输出最终结果（针对用户输入的年限 t）
print(f"\n本金：{P} 元")
print(f"年利率：{r_input}%")
print(f"存期：{t} 年，每年复利 {n} 次")
print(f"最终本息和：{final_amount} 元")

# ============== 复利 vs 单利对比表 ==============

# 复利公式：A = P * (1 + r/n)^(n*t)   ——"利滚利"，利息也参与下期计息
# 单利公式：A = P * (1 + r*t)         ——利息只按原始本金计算，不滚动
# 对比年限固定为 10、20、30 年，直观展示复利的长期优势

# 表头：使用 f-string 的左对齐格式 <N，N 为列宽
print("\n" + "=" * 60)
print("复利 vs 单利对比表")
print("=" * 60)
# 列名：年限 | 复利终值 | 单利终值 | 差额
print(f"{'年限(年)':<10}{'复利终值(元)':<18}{'单利终值(元)':<18}{'差额(元)':<18}")
print("-" * 60)

# 遍历三个对比年限 [10, 20, 30]
for years in [10, 20, 30]:
    # 复利终值：本金 × (1 + 单期利率)^(总期数)
    # 即 P * (1 + r/n)^(n*years)
    A_compound = P * (1 + r / n) ** (n * years)

    # 单利终值：本金 × (1 + 年利率 × 年数)
    # 即 P * (1 + r * years)，利息不滚动
    A_simple = P * (1 + r * years)

    # 差额 = 复利终值 - 单利终值，体现"利滚利"多赚的部分
    diff = A_compound - A_simple

    # 输出一行：保留两位小数，左对齐对齐列宽
    print(f"{years:<10}{round(A_compound, 2):<18}{round(A_simple, 2):<18}{round(diff, 2):<18}")

# 表尾提示
print("=" * 60)
print("注：差额 = 复利终值 - 单利终值，年限越长差额越大，体现复利效应。")
