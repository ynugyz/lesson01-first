# 复利计算程序（交互式）
# 复利公式: A = P * (1 + r)^n
# 其中:
#   A = 本息和（最终金额）
#   P = 本金（初始投资金额）
#   r = 年利率（每年的利息比率）
#   n = 存款年数（复利计算的期数）

# 第 1 步: 用户输入本金 P
# float() 将输入字符串转为浮点数
P = float(input("请输入本金（元）: "))

# 第 2 步: 用户输入年利率 r, 并做合法性校验
# 利率不能为负, 若输入负数则提示并要求重输
while True:
    r = float(input("请输入年利率（如 0.05 表示 5%）: "))
    if r < 0:  # 利率为负, 不合法
        print("利率不能为负, 请重新输入。")
    else:  # 利率合法, 退出循环
        break

# 第 3 步: 用户输入存期 n
# 每年复利 1 次, 期数就等于年数
n = int(input("请输入存期（年）: "))

# 第 4 步: 套用复利公式 A = P * (1 + r)^n
# (1 + r) 表示 1 元本金经过 1 年后变成 1 + 利息
# (1 + r)^n 表示经过 n 年复利后的累计增长倍数
# 乘以 P 即得到最终本息和
A = P * (1 + r) ** n

# 第 5 步: 输出结果, 保留两位小数
# 使用 :.2f 格式化, 将浮点数四舍五入到小数点后 2 位
print(f"本金: {P} 元")
print(f"年利率: {r * 100}%")
print(f"存期: {n} 年")
print(f"最终本息和: {A:.2f} 元")
